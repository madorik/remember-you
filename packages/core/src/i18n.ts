export const MESSAGES: Record<Locale, Messages> = { ko, en };

export type Vars = Record<string, string | number>;

// 받침 있을 때 꼴 → 받침 없을 때 꼴
const JOSA: Record<string, string> = { 이에요: "예요", 이: "가", 을: "를", 은: "는", 과: "와", 으로: "로" };

/** 마지막 글자에 받침이 있는지. 한글이 아니면(영문·숫자) 받침 없는 것으로 본다 */
function hasBatchim(word: string): { batchim: boolean; rieul: boolean } {
  const last = word.trim().slice(-1);
  const code = last.charCodeAt(0) - 0xac00;
  if (code < 0 || code > 11171) return { batchim: false, rieul: false };
  const jong = code % 28;
  return { batchim: jong !== 0, rieul: jong === 8 };
}

/** "생일" + 이에요 → "생일이에요", "데이트" + 이에요 → "데이트예요" */
export function josa(word: string, form: string): string {
  const alt = JOSA[form];
  if (alt === undefined) return word + form;
  const { batchim, rieul } = hasBatchim(word);
  if (form === "으로") return word + (batchim && !rieul ? "으로" : "로");
  return word + (batchim ? form : alt);
}

/** 이름 뒤에 '님'을 붙이지 않는 이름: 가족을 부르는 말(아빠님·아내님은 어색하다)이거나 이미 '님'·'씨'로 끝나는 것 */
const KIN = new Set([
  "엄마", "아빠", "어머니", "아버지", "아내", "와이프", "집사람", "남편", "신랑", "할머니", "할아버지", "외할머니", "외할아버지", "친할머니", "친할아버지",
  "이모", "삼촌", "고모", "이모부", "고모부", "외삼촌", "큰아빠", "작은아빠", "큰엄마", "작은엄마", "오빠", "형", "누나", "언니", "동생", "아들", "딸",
  "장모", "장인", "시어머니", "시아버지", "처제", "처남", "형수", "올케", "며느리", "사위", "손녀", "손자", "조카", "형부", "매형", "매제",
  "애인", "여친", "남친", "여자친구", "남자친구", "자기",
]);

export function needsHonorific(name: string): boolean {
  const n = name.trim();
  return !!n && !KIN.has(n) && !/(님|씨)$/.test(n);
}

/** 템플릿의 {이름}을 값으로 바꾼다. {이름|이에요}처럼 쓰면 받침에 맞춰 조사를 붙이고, {n|day,days}처럼 쓰면 1이냐에 따라 단수·복수를 고른다.
 *  {이름}님… 은 이름이 가족 호칭이면 '님'을 빼고 뒤 조사를 받침에 맞춘다("아빠님이" → "아빠가", "{name}님에게" → "아빠에게") */
export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const template = MESSAGES[locale][key] ?? ko[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)(?:\|([^}]+))?\}(?:(님)(에게|한테|께|을|이|은|과|의|도)?)?/g, (m, name: string, form?: string, honor?: string, particle?: string) => {
    if (!(name in vars)) return m;
    const value = String(vars[name]);
    // {n|day,days}: 1이면 앞, 아니면 뒤(영어 복수형)
    if (form?.includes(",")) {
      const [one, many] = form.split(",");
      return (Number(value) === 1 ? one : many) + (honor ?? "") + (particle ?? "");
    }
    if (form) return josa(value, form) + (honor ?? "") + (particle ?? "");
    if (!honor || needsHonorific(value)) return value + (honor ?? "") + (particle ?? "");
    // 가족 호칭: '님'은 빼고 조사는 받침에 맞춘다
    return value + (particle && JOSA[particle] !== undefined ? josa(value, particle).slice(value.length) : (particle ?? ""));
  });
}

/** 템플릿 안의 변수 이름 목록(테스트에서 두 언어가 같은 변수를 쓰는지 본다) */
export function placeholders(template: string): string[] {
  return [...new Set([...template.matchAll(/\{(\w+)(?:\|[^}]+)?\}/g)].map((m) => m[1]!))].sort();
}
