/** 가이드에 맞는 선물: 태그가 많이 겹치는 것부터, 가격대마다 다섯 */
export function guidePicks(g: Guide, catalog: CatalogGift[] = GIFT_CATALOG): { band: PriceBand; items: CatalogGift[] }[] {
  const bands = g.bands ?? [...PRICE_BANDS];
  const scored = catalog
    .map((x, i) => {
      // 제철 전용(사진·파트너스 링크 전)은 늘 열려 있는 가이드에 싣지 않는다
      if (x.seasonOnly) return null;
      if (g.without?.some((t) => x.tags.includes(t))) return null;
      if (g.ages && (x.ages[1] < g.ages[0] || x.ages[0] > g.ages[1])) return null;
      const hits = x.tags.filter((t) => g.tags.includes(t)).length;
      return hits ? { x, i, hits } : null;
    })
    .filter((v): v is { x: CatalogGift; i: number; hits: number } => !!v);
  return bands
    .map((band) => ({
      band,
      items: scored
        .filter((s) => s.x.band === band)
        .sort((a, b) => b.hits - a.hits || a.i - b.i)
        .slice(0, 5)
        .map((s) => s.x),
    }))
    .filter((b) => b.items.length);
}

/** 가격대마다 묻고 답하기(AI 답변용): "부모님 선물 5만원대로는 무엇이 좋을까요?" */
export function bandFaq(g: Guide, picks: { band: PriceBand; items: CatalogGift[] }[]): { q: string; a: string }[] {
  return picks.map(({ band, items }) => ({
    q: `${g.who} 선물 ${BAND_NAME[band]}로는 무엇이 좋을까요?`,
    a: `${items.map((x) => x.q).join(", ")} 같은 선물이 있어요. 쿠팡 랭킹 위쪽 상품 중에서 ${BAND_NAME[band]}에 드는 것으로 골랐어요.`,
  }));
}
